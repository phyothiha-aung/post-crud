import { NextResponse } from "next/server";

export type PostInput = { title: string; content: string | null };

type ValidationResult<T> =
  { ok: true; data: T } | { ok: false; errors: Record<string, string> };

/**
 * Validate a post payload. With `partial`, every field is optional
 * (used by PATCH), but any field that is present must still be valid.
 */
export function validatePostInput(
  body: unknown,
  { partial = false }: { partial?: boolean } = {},
): ValidationResult<Partial<PostInput>> {
  if (typeof body !== "object" || body === null || Array.isArray(body)) {
    return {
      ok: false,
      errors: { body: "Request body must be a JSON object" },
    };
  }

  const { title, content } = body as Record<string, unknown>;
  const errors: Record<string, string> = {};
  const data: Partial<PostInput> = {};

  if (title === undefined) {
    if (!partial) errors.title = "Title is required";
  } else if (typeof title !== "string" || title.trim() === "") {
    errors.title = "Title must be a non-empty string";
  } else if (title.length > 255) {
    errors.title = "Title must be at most 255 characters";
  } else {
    data.title = title.trim();
  }

  if (content !== undefined) {
    if (content !== null && typeof content !== "string") {
      errors.content = "Content must be a string or null";
    } else {
      data.content = content;
    }
  }

  if (
    partial &&
    Object.keys(errors).length === 0 &&
    Object.keys(data).length === 0
  ) {
    errors.body = "Provide at least one of: title, content";
  }

  return Object.keys(errors).length > 0
    ? { ok: false, errors }
    : { ok: true, data };
}

const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Validate a post id (a UUID, normally v7 generated by the client or server). Returns it lower-cased, or null. */
export function parseId(raw: unknown): string | null {
  return typeof raw === "string" && UUID_RE.test(raw)
    ? raw.toLowerCase()
    : null;
}

/** Parse an ISO-8601 timestamp, or null when missing/invalid. */
export function parseDate(raw: unknown): Date | null {
  if (typeof raw !== "string" || raw === "") return null;
  const date = new Date(raw);
  return Number.isNaN(date.getTime()) ? null : date;
}

/**
 * Pull only returns rows whose updatedAt is at least this old. updatedAt is
 * stamped when a write runs but the row only becomes visible when its
 * transaction commits, so a recent timestamp may still have older-stamped
 * rows about to appear behind it. Rows inside the window come on the next pull.
 */
export const PULL_SAFETY_LAG_MS = 2_000;

/**
 * Sync cursor: the (updatedAt, id) of the last row a client has pulled,
 * encoded as opaque base64url JSON so clients treat it as a token.
 */
export type SyncCursor = { updatedAt: Date; id: string };

export function encodeCursor({ updatedAt, id }: SyncCursor): string {
  return Buffer.from(
    JSON.stringify({ u: updatedAt.toISOString(), i: id }),
  ).toString("base64url");
}

export function decodeCursor(raw: string): SyncCursor | null {
  try {
    const { u, i } = JSON.parse(Buffer.from(raw, "base64url").toString());
    const updatedAt = parseDate(u);
    const id = parseId(i);
    return updatedAt && id ? { updatedAt, id } : null;
  } catch {
    return null;
  }
}

export type PushChange =
  | {
      op: "upsert";
      id: string;
      title: string;
      content: string | null;
      baseUpdatedAt: Date | null;
    }
  | { op: "delete"; id: string; baseUpdatedAt: Date | null };

/** Validate one entry of a sync push batch. */
export function validatePushChange(
  raw: unknown,
): ValidationResult<PushChange> & { id: string | null } {
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) {
    return {
      ok: false,
      id: null,
      errors: { change: "Change must be an object" },
    };
  }
  const change = raw as Record<string, unknown>;
  const errors: Record<string, string> = {};

  const id = parseId(change.id);
  if (id === null) errors.id = "id must be a UUID";

  let baseUpdatedAt: Date | null = null;
  if (change.baseUpdatedAt !== undefined && change.baseUpdatedAt !== null) {
    baseUpdatedAt = parseDate(change.baseUpdatedAt);
    if (baseUpdatedAt === null)
      errors.baseUpdatedAt = "baseUpdatedAt must be an ISO-8601 timestamp";
  }

  if (change.op === "delete") {
    return Object.keys(errors).length > 0
      ? { ok: false, id, errors }
      : { ok: true, id, data: { op: "delete", id: id!, baseUpdatedAt } };
  }
  if (change.op !== "upsert") {
    errors.op = 'op must be "upsert" or "delete"';
    return { ok: false, id, errors };
  }

  const fields = validatePostInput({
    title: change.title,
    content: change.content,
  });
  if (!fields.ok) Object.assign(errors, fields.errors);

  if (Object.keys(errors).length > 0) return { ok: false, id, errors };
  const { title, content = null } = (fields as { data: PostInput }).data;
  return {
    ok: true,
    id,
    data: { op: "upsert", id: id!, title, content, baseUpdatedAt },
  };
}

/** Read a positive integer query param, falling back to a default and clamping to max. */
export function parsePositiveInt(
  raw: string | null,
  fallback: number,
  max = Infinity,
): number {
  if (raw === null || !/^\d+$/.test(raw)) return fallback;
  const n = Number(raw);
  return n < 1 ? fallback : Math.min(n, max);
}

/** Escape LIKE wildcards so user input is matched literally. */
export function escapeLike(value: string): string {
  return value.replace(/[\\%_]/g, (c) => `\\${c}`);
}

export async function readJson(
  req: Request,
): Promise<unknown | typeof INVALID_JSON> {
  try {
    return await req.json();
  } catch {
    return INVALID_JSON;
  }
}
export const INVALID_JSON = Symbol("invalid-json");

export const errorResponse = (
  status: number,
  message: string,
  errors?: Record<string, string>,
) => NextResponse.json({ message, ...(errors && { errors }) }, { status });
